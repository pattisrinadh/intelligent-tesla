import React, { useState, useEffect } from 'react';
import type { CustomAgent } from '../../types';
import { agentApi } from '../../lib/api';
import { X, Bot, Sparkles, Check, AlertCircle } from 'lucide-react';

interface CreateAgentModalProps {
  isOpen: boolean;
  onClose: () => void;
  onSuccess: (agent: CustomAgent) => void;
  editingAgent?: CustomAgent | null;
}

const AVAILABLE_CAPABILITIES = [
  'Code Generation',
  'Web Research',
  'File Operations',
  'Database',
  'API Calls',
  'Testing',
  'Reasoning',
];

const DEFAULT_MODELS = [
  { id: 'qwen.qwen3-coder-next', name: 'Qwen 3 Coder Next (Specialized for Code)', provider: 'bedrock' },
  { id: 'deepseek.v3.2', name: 'DeepSeek V3.2 (Reasoning & General)', provider: 'bedrock' },
  { id: 'qwen.qwen3-32b', name: 'Qwen 3 32B (Balanced Fast)', provider: 'bedrock' },
  { id: 'zai.glm-4.7-flash', name: 'GLM 4.7 Flash (Ultra Low Latency)', provider: 'bedrock' },
];

export const CreateAgentModal: React.FC<CreateAgentModalProps> = ({
  isOpen,
  onClose,
  onSuccess,
  editingAgent,
}) => {
  const [name, setName] = useState('');
  const [id, setId] = useState('');
  const [description, setDescription] = useState('');
  const [role, setRole] = useState('');
  const [systemPrompt, setSystemPrompt] = useState('');
  const [provider, setProvider] = useState('bedrock');
  const [model, setModel] = useState('qwen.qwen3-coder-next');
  const [temperature, setTemperature] = useState(0.7);
  const [maxTokens, setMaxTokens] = useState(2048);
  const [capabilities, setCapabilities] = useState<string[]>([
    'Code Generation',
    'Reasoning',
    'Testing',
  ]);
  const [error, setError] = useState<string | null>(null);
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [idAutoGenerated, setIdAutoGenerated] = useState(true);

  useEffect(() => {
    if (editingAgent) {
      setName(editingAgent.name);
      setId(editingAgent.id);
      setDescription(editingAgent.description);
      setRole(editingAgent.role);
      setSystemPrompt(editingAgent.systemPrompt);
      setProvider(editingAgent.provider || 'bedrock');
      setModel(editingAgent.model || 'qwen.qwen3-coder-next');
      setTemperature(editingAgent.temperature ?? 0.7);
      setMaxTokens(editingAgent.maxTokens ?? 2048);
      setCapabilities(editingAgent.capabilities || []);
      setIdAutoGenerated(false);
    } else {
      setName('');
      setId('');
      setDescription('');
      setRole('');
      setSystemPrompt(
        'You are a professional software engineer. Analyze the user\'s requirement, create a solution, and return a clear implementation.'
      );
      setProvider('bedrock');
      setModel('qwen.qwen3-coder-next');
      setTemperature(0.7);
      setMaxTokens(2048);
      setCapabilities(['Code Generation', 'Reasoning', 'Testing']);
      setIdAutoGenerated(true);
    }
    setError(null);
  }, [editingAgent, isOpen]);

  const handleNameChange = (val: string) => {
    setName(val);
    if (idAutoGenerated && !editingAgent) {
      setId(val.toLowerCase().replace(/[^a-z0-9_-]/g, '-'));
    }
  };

  const toggleCapability = (cap: string) => {
    setCapabilities(prev =>
      prev.includes(cap) ? prev.filter(c => c !== cap) : [...prev, cap]
    );
  };

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setError(null);

    // Validation
    if (!name.trim()) {
      setError('Agent Name is required.');
      return;
    }
    if (!role.trim()) {
      setError('Agent Role is required.');
      return;
    }
    if (!systemPrompt.trim()) {
      setError('Agent Instructions (System Prompt) are required.');
      return;
    }

    const finalId = id.trim() || name.trim().toLowerCase().replace(/[^a-z0-9_-]/g, '-');

    setIsSubmitting(true);
    try {
      if (editingAgent) {
        const updated = await agentApi.updateAgent(editingAgent.id, {
          name: name.trim(),
          description: description.trim(),
          role: role.trim(),
          systemPrompt: systemPrompt.trim(),
          provider,
          model,
          temperature,
          maxTokens,
          capabilities,
        });
        onSuccess(updated);
      } else {
        const created = await agentApi.createAgent({
          id: finalId,
          name: name.trim(),
          description: description.trim(),
          role: role.trim(),
          systemPrompt: systemPrompt.trim(),
          provider,
          model,
          temperature,
          maxTokens,
          capabilities,
          status: 'READY',
        });
        onSuccess(created);
      }
      onClose();
    } catch (err: any) {
      setError(err.message || 'Failed to save agent');
    } finally {
      setIsSubmitting(false);
    }
  };

  if (!isOpen) return null;

  return (
    <div
      style={{
        position: 'fixed',
        inset: 0,
        zIndex: 1000,
        display: 'flex',
        alignItems: 'center',
        justifyContent: 'center',
        background: 'rgba(0, 0, 0, 0.75)',
        backdropFilter: 'blur(8px)',
        padding: '20px',
        overflowY: 'auto',
      }}
    >
      <div
        className="glass-card"
        style={{
          width: '100%',
          maxWidth: '680px',
          maxHeight: '90vh',
          display: 'flex',
          flexDirection: 'column',
          background: 'var(--bg-secondary)',
          border: '1px solid var(--border-glow)',
          borderRadius: '16px',
          boxShadow: '0 25px 50px -12px rgba(0, 0, 0, 0.6), 0 0 30px rgba(99, 102, 241, 0.2)',
          overflow: 'hidden',
          animation: 'fadeIn 0.2s ease',
        }}
      >
        {/* Header */}
        <div
          style={{
            padding: '20px 24px',
            borderBottom: '1px solid var(--border)',
            display: 'flex',
            alignItems: 'center',
            justifyContent: 'space-between',
            background: 'rgba(255, 255, 255, 0.02)',
          }}
        >
          <div style={{ display: 'flex', alignItems: 'center', gap: '12px' }}>
            <div
              style={{
                width: 40,
                height: 40,
                borderRadius: '10px',
                background: 'linear-gradient(135deg, rgba(99,102,241,0.3), rgba(139,92,246,0.2))',
                border: '1px solid rgba(99,102,241,0.4)',
                display: 'flex',
                alignItems: 'center',
                justifyContent: 'center',
                color: '#818cf8',
              }}
            >
              <Bot size={22} />
            </div>
            <div>
              <h2 style={{ fontSize: '18px', fontWeight: 800, color: 'var(--text-primary)', margin: 0 }}>
                {editingAgent ? 'Edit Agent' : 'Create New AI Agent'}
              </h2>
              <p style={{ fontSize: '12px', color: 'var(--text-muted)', margin: 0 }}>
                Configure role, instructions, model parameters and capabilities
              </p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="btn btn-secondary"
            style={{ padding: '6px', borderRadius: '8px', color: 'var(--text-muted)' }}
          >
            <X size={18} />
          </button>
        </div>

        {/* Form Body */}
        <form onSubmit={handleSubmit} style={{ overflowY: 'auto', padding: '24px', flex: 1 }}>
          {error && (
            <div
              style={{
                marginBottom: '20px',
                padding: '12px 16px',
                borderRadius: '8px',
                background: 'rgba(239, 68, 68, 0.12)',
                border: '1px solid rgba(239, 68, 68, 0.3)',
                color: '#f87171',
                fontSize: '13px',
                display: 'flex',
                alignItems: 'center',
                gap: '8px',
              }}
            >
              <AlertCircle size={16} style={{ flexShrink: 0 }} />
              <span>{error}</span>
            </div>
          )}

          {/* Section 1: Basic Information */}
          <div style={{ marginBottom: '24px' }}>
            <div
              style={{
                fontSize: '12px',
                fontWeight: 700,
                color: '#818cf8',
                letterSpacing: '0.08em',
                textTransform: 'uppercase',
                marginBottom: '12px',
                display: 'flex',
                alignItems: 'center',
                gap: '6px',
              }}
            >
              <Sparkles size={14} /> Basic Information
            </div>

            <div style={{ display: 'grid', gridTemplateColumns: '1fr 1fr', gap: '14px', marginBottom: '14px' }}>
              <div>
                <label style={{ display: 'block', fontSize: '12px', fontWeight: 600, color: 'var(--text-secondary)', marginBottom: '6px' }}>
                  Agent Name <span style={{ color: '#ef4444' }}>*</span>
                </label>
                <input
                  type="text"
                  placeholder="e.g. Code Builder"
                  value={name}
                  onChange={e => handleNameChange(e.target.value)}
                  style={{
                    width: '100%',
                    padding: '10px 12px',
                    borderRadius: '8px',
                    background: 'var(--bg-glass)',
                    border: '1px solid var(--border)',
                    color: 'var(--text-primary)',
                    fontSize: '13px',
                    outline: 'none',
                  }}
                  required
                />
              </div>

              <div>
                <label style={{ display: 'block', fontSize: '12px', fontWeight: 600, color: 'var(--text-secondary)', marginBottom: '6px' }}>
                  Agent ID
                </label>
                <input
                  type="text"
                  placeholder="e.g. code-builder"
                  value={id}
                  disabled={!!editingAgent}
                  onChange={e => {
                    setId(e.target.value);
                    setIdAutoGenerated(false);
                  }}
                  style={{
                    width: '100%',
                    padding: '10px 12px',
                    borderRadius: '8px',
                    background: editingAgent ? 'rgba(0,0,0,0.3)' : 'var(--bg-glass)',
                    border: '1px solid var(--border)',
                    color: editingAgent ? 'var(--text-muted)' : 'var(--text-primary)',
                    fontSize: '13px',
                    fontFamily: 'var(--font-mono)',
                    outline: 'none',
                  }}
                />
              </div>
            </div>

            <div style={{ display: 'grid', gridTemplateColumns: '1fr 1fr', gap: '14px', marginBottom: '14px' }}>
              <div>
                <label style={{ display: 'block', fontSize: '12px', fontWeight: 600, color: 'var(--text-secondary)', marginBottom: '6px' }}>
                  Agent Role <span style={{ color: '#ef4444' }}>*</span>
                </label>
                <input
                  type="text"
                  placeholder="e.g. Software Engineer"
                  value={role}
                  onChange={e => setRole(e.target.value)}
                  style={{
                    width: '100%',
                    padding: '10px 12px',
                    borderRadius: '8px',
                    background: 'var(--bg-glass)',
                    border: '1px solid var(--border)',
                    color: 'var(--text-primary)',
                    fontSize: '13px',
                    outline: 'none',
                  }}
                  required
                />
              </div>

              <div>
                <label style={{ display: 'block', fontSize: '12px', fontWeight: 600, color: 'var(--text-secondary)', marginBottom: '6px' }}>
                  Description
                </label>
                <input
                  type="text"
                  placeholder="e.g. Builds application code based on requirements"
                  value={description}
                  onChange={e => setDescription(e.target.value)}
                  style={{
                    width: '100%',
                    padding: '10px 12px',
                    borderRadius: '8px',
                    background: 'var(--bg-glass)',
                    border: '1px solid var(--border)',
                    color: 'var(--text-primary)',
                    fontSize: '13px',
                    outline: 'none',
                  }}
                />
              </div>
            </div>
          </div>

          {/* Section 2: Agent Instructions */}
          <div style={{ marginBottom: '24px' }}>
            <div
              style={{
                fontSize: '12px',
                fontWeight: 700,
                color: '#818cf8',
                letterSpacing: '0.08em',
                textTransform: 'uppercase',
                marginBottom: '8px',
              }}
            >
              Agent Instructions (System Prompt) <span style={{ color: '#ef4444' }}>*</span>
            </div>
            <textarea
              rows={4}
              placeholder="Define how the agent should think, reason, and respond to user requests..."
              value={systemPrompt}
              onChange={e => setSystemPrompt(e.target.value)}
              style={{
                width: '100%',
                padding: '12px',
                borderRadius: '8px',
                background: 'var(--bg-glass)',
                border: '1px solid var(--border)',
                color: 'var(--text-primary)',
                fontSize: '13px',
                lineHeight: '1.5',
                fontFamily: 'inherit',
                resize: 'vertical',
                outline: 'none',
              }}
              required
            />
          </div>

          {/* Section 3: Model Configuration */}
          <div style={{ marginBottom: '24px' }}>
            <div
              style={{
                fontSize: '12px',
                fontWeight: 700,
                color: '#818cf8',
                letterSpacing: '0.08em',
                textTransform: 'uppercase',
                marginBottom: '12px',
              }}
            >
              Model Configuration
            </div>

            <div style={{ display: 'grid', gridTemplateColumns: '1fr 1.5fr', gap: '14px', marginBottom: '14px' }}>
              <div>
                <label style={{ display: 'block', fontSize: '12px', fontWeight: 600, color: 'var(--text-secondary)', marginBottom: '6px' }}>
                  Provider
                </label>
                <select
                  value={provider}
                  onChange={e => setProvider(e.target.value)}
                  style={{
                    width: '100%',
                    padding: '10px 12px',
                    borderRadius: '8px',
                    background: '#1a1f36',
                    border: '1px solid var(--border)',
                    color: 'var(--text-primary)',
                    fontSize: '13px',
                    outline: 'none',
                  }}
                >
                  <option value="bedrock">AWS Bedrock Mantle (OpenAI-Compatible)</option>
                  <option value="openai">OpenAI Compatible (Custom)</option>
                </select>
              </div>

              <div>
                <label style={{ display: 'block', fontSize: '12px', fontWeight: 600, color: 'var(--text-secondary)', marginBottom: '6px' }}>
                  Model
                </label>
                <select
                  value={model}
                  onChange={e => setModel(e.target.value)}
                  style={{
                    width: '100%',
                    padding: '10px 12px',
                    borderRadius: '8px',
                    background: '#1a1f36',
                    border: '1px solid var(--border)',
                    color: 'var(--text-primary)',
                    fontSize: '13px',
                    outline: 'none',
                  }}
                >
                  {DEFAULT_MODELS.map(m => (
                    <option key={m.id} value={m.id}>
                      {m.name}
                    </option>
                  ))}
                </select>
              </div>
            </div>

            <div style={{ display: 'grid', gridTemplateColumns: '1fr 1fr', gap: '14px' }}>
              <div>
                <div style={{ display: 'flex', justifyContent: 'space-between', marginBottom: '6px' }}>
                  <label style={{ fontSize: '12px', fontWeight: 600, color: 'var(--text-secondary)' }}>
                    Temperature
                  </label>
                  <span style={{ fontSize: '12px', fontFamily: 'var(--font-mono)', color: '#818cf8' }}>
                    {temperature.toFixed(2)}
                  </span>
                </div>
                <input
                  type="range"
                  min="0"
                  max="1"
                  step="0.05"
                  value={temperature}
                  onChange={e => setTemperature(parseFloat(e.target.value))}
                  style={{ width: '100%', accentColor: 'var(--primary)' }}
                />
              </div>

              <div>
                <label style={{ display: 'block', fontSize: '12px', fontWeight: 600, color: 'var(--text-secondary)', marginBottom: '6px' }}>
                  Maximum Tokens
                </label>
                <input
                  type="number"
                  min="256"
                  max="8192"
                  step="256"
                  value={maxTokens}
                  onChange={e => setMaxTokens(parseInt(e.target.value, 10) || 2048)}
                  style={{
                    width: '100%',
                    padding: '9px 12px',
                    borderRadius: '8px',
                    background: 'var(--bg-glass)',
                    border: '1px solid var(--border)',
                    color: 'var(--text-primary)',
                    fontSize: '13px',
                    fontFamily: 'var(--font-mono)',
                    outline: 'none',
                  }}
                />
              </div>
            </div>
          </div>

          {/* Section 4: Capabilities */}
          <div style={{ marginBottom: '24px' }}>
            <div
              style={{
                fontSize: '12px',
                fontWeight: 700,
                color: '#818cf8',
                letterSpacing: '0.08em',
                textTransform: 'uppercase',
                marginBottom: '10px',
              }}
            >
              Capabilities
            </div>
            <div style={{ display: 'grid', gridTemplateColumns: 'repeat(auto-fill, minmax(180px, 1fr))', gap: '10px' }}>
              {AVAILABLE_CAPABILITIES.map(cap => {
                const active = capabilities.includes(cap);
                return (
                  <div
                    key={cap}
                    onClick={() => toggleCapability(cap)}
                    style={{
                      display: 'flex',
                      alignItems: 'center',
                      gap: '10px',
                      padding: '10px 12px',
                      borderRadius: '8px',
                      background: active ? 'rgba(99, 102, 241, 0.12)' : 'var(--bg-glass)',
                      border: `1px solid ${active ? 'rgba(99, 102, 241, 0.4)' : 'var(--border)'}`,
                      cursor: 'pointer',
                      transition: 'all 0.15s ease',
                    }}
                  >
                    <div
                      style={{
                        width: 18,
                        height: 18,
                        borderRadius: '4px',
                        background: active ? 'var(--primary)' : 'rgba(255,255,255,0.06)',
                        border: `1px solid ${active ? 'var(--primary)' : 'var(--border)'}`,
                        display: 'flex',
                        alignItems: 'center',
                        justifyContent: 'center',
                        color: '#fff',
                        fontSize: '12px',
                      }}
                    >
                      {active && <Check size={12} strokeWidth={3} />}
                    </div>
                    <span style={{ fontSize: '13px', color: active ? 'var(--text-primary)' : 'var(--text-secondary)' }}>
                      {cap}
                    </span>
                  </div>
                );
              })}
            </div>
          </div>

          {/* Footer Actions */}
          <div
            style={{
              display: 'flex',
              justifyContent: 'flex-end',
              gap: '12px',
              paddingTop: '16px',
              borderTop: '1px solid var(--border)',
            }}
          >
            <button
              type="button"
              onClick={onClose}
              className="btn btn-secondary"
              disabled={isSubmitting}
            >
              Cancel
            </button>
            <button
              type="submit"
              className="btn btn-primary"
              disabled={isSubmitting}
              style={{ minWidth: '130px', justifyContent: 'center' }}
            >
              {isSubmitting ? (
                <span>Saving...</span>
              ) : (
                <span>{editingAgent ? 'Save Changes' : 'Create Agent'}</span>
              )}
            </button>
          </div>
        </form>
      </div>
    </div>
  );
};
